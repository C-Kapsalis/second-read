"""Shared writer for the Second Read benchmark cases.

Each case script in cases/ parses its benchmark file (a Markdown answer sheet
of planted flaws, decoys and facts) and calls write_case(), which writes

  benchmarks/cases/<name>/{case.yaml, prompt.md, scaffold.sh, graders/*.md}

in the format `claude plugin eval` reads. Rebuild every case:

  python3 benchmarks/builder/build_all.py
"""

from __future__ import annotations

import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CASES = REPO / "benchmarks" / "cases"

REPORT_LINE = "Save report.md in the current working directory, not inside resources/."
EOF_MARK = "SECOND_READ_EOF"


def write_case(
    name: str,
    files: dict[str, str],
    prompt: str,
    graders: list[tuple[str, int, str]],
    *,
    skill_match: str,
    output: str = "report.md",
    runs: int = 3,
) -> None:
    """files: {"resources/x.md": text}. graders: (slug, weight, body), judged on `output`.

    skill_match: regex the skill-fired grader matches against the Skill tool input.
    """
    assert all(k.startswith("resources/") for k in files), "fixtures live in resources/"
    case = CASES / name
    if case.exists():
        shutil.rmtree(case)
    (case / "graders").mkdir(parents=True)

    (case / "case.yaml").write_text(
        f'schema_version: "1.1"\nname: {name}\nruns: {runs}\n'
        "context:\n  scaffold_script: scaffold.sh\n"
    )

    save_line = REPORT_LINE if output == "report.md" else (
        f"Save {output} in the current working directory, not inside resources/."
    )
    (case / "prompt.md").write_text(
        "---\nmax_turns: 40\ntimeout_seconds: 900\n"
        "allowed_tools: [Read, Glob, Grep, Skill, Write]\n---\n\n"
        f"{prompt.strip()}\n\n{save_line}\n"
    )

    lines = [
        "#!/usr/bin/env bash",
        "# Writes this case's fixture into the run's workspace (both arms see the same files).",
        "# Generated by benchmarks/builder; edit the benchmark file there, not this file.",
        "set -euo pipefail",
        "mkdir -p resources",
    ]
    for path, text in files.items():
        assert EOF_MARK not in text
        lines += [f"cat > {path} <<'{EOF_MARK}'", text.rstrip("\n"), EOF_MARK]
    scaffold = case / "scaffold.sh"
    scaffold.write_text("\n".join(lines) + "\n")
    scaffold.chmod(0o755)

    (case / "graders" / "skill-fired.md").write_text(
        "---\ntype: tool_used\ntool: Skill\n"
        f"input_match: '{skill_match}'\n---\n"
    )
    for slug, weight, body in graders:
        (case / "graders" / f"{slug}.md").write_text(
            f"---\ntype: llm\nweight: {weight}\nfocus: {{ source: file, path: {output} }}\n---\n\n"
            f"{body.strip()}\n"
        )
